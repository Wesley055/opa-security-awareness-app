import { ConflictException, BadRequestException } from "@nestjs/common";
import { DutyService } from "./duty.service";

const op = { id: "op", role: "FACILITY_OPERATOR", facilityId: "fac", isActive: true, membershipState: "ACTIVE", photoStatus: null, firstName: "P", lastName: "C" };

function service(user: object, extra: Record<string, unknown> = {}) {
  const prisma: any = {
    user: { findUnique: jest.fn().mockResolvedValue(user), findMany: jest.fn().mockResolvedValue([]) },
    dutyShift: { findFirst: jest.fn(), findMany: jest.fn().mockResolvedValue([]), create: jest.fn() },
    dutyReport: { findFirst: jest.fn() },
    administrativeAuditEvent: { create: jest.fn() },
    ...extra,
  };
  prisma.$transaction = jest.fn((fn: any) => (typeof fn === "function" ? fn(prisma) : Promise.all(fn)));
  return { svc: new DutyService(prisma, { send: jest.fn() } as any), prisma };
}

describe("duty safeguards", () => {
  it("refuses to START a shift without an approved photo, saying emergency response is unaffected", async () => {
    const { svc, prisma } = service(op);
    await expect(svc.start("op")).rejects.toBeInstanceOf(ConflictException);
    await svc.start("op").catch((e) => expect(JSON.stringify(e.getResponse())).toMatch(/still respond to every emergency/));
    expect(prisma.dutyShift.create).not.toHaveBeenCalled();
  });

  it("only acknowledges operator-submitted reports (a backup never closes the obligation)", async () => {
    const { svc } = service(op);
    (svc as any).prisma.dutyReport.findFirst.mockResolvedValue({ id: "r", origin: "SYSTEM_GENERATED", acknowledgedAt: null });
    await expect(svc.acknowledge("admin", "fac", "r")).rejects.toBeInstanceOf(BadRequestException);
  });

  it("lists a system-closed shift without an operator report as OPERATOR_REPORT_MISSING", async () => {
    const { svc, prisma } = service(op);
    prisma.dutyShift.findMany.mockResolvedValue([{ id: "s", startedAt: new Date(), endedAt: new Date(), endedBy: "SYSTEM", operator: { firstName: "P", lastName: "C" }, reports: [{ id: "b", origin: "SYSTEM_GENERATED", submittedAt: new Date(), late: false, acknowledgedAt: null, document: { totals: { raised: 0 } } }] }]);
    const row = (await svc.list("admin", "fac", false))[0]!;
    expect(row.status).toBe("OPERATOR_REPORT_MISSING");
    expect(row.operatorReport).toBeNull();
    expect(row.systemReport?.label).toBe("Generated by OPA. Not submitted by an operator.");
  });

  it("rejects non-operators", async () => {
    const { svc } = service({ ...op, role: "FACILITY_ADMIN" });
    await expect(svc.current("x")).rejects.toThrow(/active facility operators/);
  });
});
