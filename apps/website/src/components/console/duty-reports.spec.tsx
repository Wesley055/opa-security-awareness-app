import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { expect, it, vi } from "vitest";
import { DutyReportList } from "./duty-reports";

const totals = { raised: 1, carriedOver: 0, acknowledged: 0, notAcknowledgedOrUnknown: 1, stillOpenAtCutoff: 1 };
const rows = [{ shiftId: "s", operatorName: "Philips Clay", startedAt: "2026-10-20T06:00:00Z", endedAt: "2026-10-20T18:00:00Z", status: "OPERATOR_REPORT_MISSING", operatorReport: null, systemReport: { id: "b", generatedAt: "2026-10-20T18:00:00Z", label: "Generated by OPA. Not submitted by an operator." }, totals }];
const backup = { id: "b", origin: "SYSTEM_GENERATED", label: "Generated by OPA. Not submitted by an operator.", operatorName: "Philips Clay", submittedAt: "2026-10-20T18:00:00Z", sourceCutoff: "2026-10-20T18:00:00Z", document: { window: { from: "2026-10-20T06:00:00Z", to: "2026-10-20T18:00:00Z" }, membersLabel: "residents", totals, incidents: { raised: [], carriedOver: [] }, sections: [] }, notes: null, handoverItems: [], acknowledgedAt: null, changedSinceReport: [] };

it("shows a missing operator report and never offers to acknowledge an OPA backup", async () => {
  const transport = vi.fn(async (path: string) => new Response(JSON.stringify(path === "duty-reports" ? rows : backup), { status: 200 }));
  render(<DutyReportList source="admin" transport={transport} />);
  expect(await screen.findByText(/Operator report missing/)).toBeTruthy();
  expect(screen.getByText(/1 operator report missing/)).toBeTruthy();
  fireEvent.click(screen.getByText("OPA backup"));
  await waitFor(() => expect(screen.getByText("Generated by OPA. Not submitted by an operator.")).toBeTruthy());
  expect(screen.getByText(/operator's own report is still required/)).toBeTruthy();
  expect(screen.queryByText("Acknowledge report")).toBeNull();
});
